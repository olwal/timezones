const slug = s => s.toLowerCase().replace(/['’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const CITIES = CITY_DATA.map(([name, country, tz, lat, lon, alias, region, id]) => ({
  name, country, tz, lat, lon,
  region: region || "",
  // Shown on the card: the state or province where that is the more useful
  // label (Santa Cruz -> California), the country otherwise.
  place: region || country,
  id: id || slug(name),
  hay: (name + " " + country + " " + (region || "") + " " +
        tz.replace(/[_/]/g, " ") + " " + alias).toLowerCase()
}));

// Same-name cities in different countries would otherwise collide and one would
// silently disappear from the lookup, so disambiguate rather than overwrite.
const BY_ID = new Map();
for (const c of CITIES) {
  if (BY_ID.has(c.id)) c.id = slug(c.name + "-" + (c.region || c.country));
  while (BY_ID.has(c.id)) c.id += "-2";
  BY_ID.set(c.id, c);
}
const DEFAULTS = ["san-francisco", "new-york", "london", "tokyo"];

